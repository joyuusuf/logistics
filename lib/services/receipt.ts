import type { Shipment, Transaction, User } from "@/types";
import { DELIVERY_TYPES, PAYMENT_METHODS, TRANSACTION_STATUS } from "@/lib/constants";
import { formatDateTime, formatNaira } from "@/lib/utils";

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] ?? c);

/** Builds a standalone, printable HTML receipt for download. */
export function receiptHtml(t: Transaction, s: Shipment | undefined, customer: User | undefined): string {
  const rows: [string, string][] = s
    ? [
        ["Base fee", formatNaira(s.price.baseFee)],
        ["Distance", formatNaira(s.price.distanceFee)],
        ["Weight", formatNaira(s.price.weightFee)],
        ["Handling", formatNaira(s.price.specialFee)],
        [s.price.serviceSurcharge < 0 ? "Scheduled discount" : "Speed surcharge", formatNaira(s.price.serviceSurcharge)],
      ]
    : [];
  return `<!doctype html><html><head><meta charset="utf-8"><title>Receipt ${esc(t.reference)}</title>
<style>body{font-family:system-ui,-apple-system,Segoe UI,sans-serif;color:#202B36;max-width:560px;margin:40px auto;padding:0 20px}
.brand{font-weight:800;font-size:24px}.brand b{color:#142C45}.brand i{color:#16A477;font-style:normal}
.muted{color:#718096;font-size:13px}table{width:100%;border-collapse:collapse;margin-top:16px}td{padding:8px 0;border-bottom:1px solid #E7EDF2;font-size:14px}
td:last-child{text-align:right}.total td{font-weight:800;font-size:18px;color:#142C45;border:0;padding-top:14px}.tag{display:inline-block;padding:2px 10px;border-radius:99px;background:#e8f6f1;color:#0f8a63;font-size:12px;font-weight:700}</style></head>
<body><div class="brand"><b>Swift</b><i>Logix</i></div><p class="muted">Delivering More, Faster. · support@swiftlogix.ng</p>
<h2 style="margin-top:28px">Payment receipt</h2><p class="muted">Receipt ${esc(t.reference)} · ${esc(formatDateTime(t.createdAt))}</p>
<p><span class="tag">${esc(TRANSACTION_STATUS[t.status].label)}</span></p>
<table><tr><td>Billed to</td><td>${esc(customer?.name ?? "-")}<br><span class="muted">${esc(customer?.email ?? "")}</span></td></tr>
${s ? `<tr><td>Shipment</td><td>${esc(s.reference)}</td></tr><tr><td>Route</td><td>${esc(s.sender.lga)}, ${esc(s.sender.state)} → ${esc(s.recipient.lga)}, ${esc(s.recipient.state)}</td></tr><tr><td>Service</td><td>${esc(DELIVERY_TYPES[s.deliveryType].label)}</td></tr>` : ""}
<tr><td>Payment method</td><td>${esc(PAYMENT_METHODS[t.method])}</td></tr>
${rows.map(([l, v]) => `<tr><td>${esc(l)}</td><td>${esc(v)}</td></tr>`).join("")}
<tr class="total"><td>Total</td><td>${esc(formatNaira(t.amount))}</td></tr></table>
<p class="muted" style="margin-top:32px">This receipt was generated by the SwiftLogix frontend demo. No real payment was processed.</p></body></html>`;
}
